export function groupOf(n: number) {
  return site.topics.groups.find((g) => n >= g.from && n <= g.to)?.name ?? '';
}

export const pad = (n: number) => String(n).padStart(2, '0');

/** [[фраза]] → лаймовый маркер. Текст безопасный: мы экранируем HTML */
export function marked(text: string) {
  const esc = text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  return esc.replace(/\[\[(.+?)\]\]/g, '<mark class="hl">$1</mark>');
}

/** Число в русском формате: 738,5 / 50 333 */
export function formatNumber(value: number, decimals = 0) {
  return value
    .toFixed(decimals)
    .replace('.', ',')
    .replace(/\B(?=(\d{3})+(?!\d))/g, '\u00a0');
}
